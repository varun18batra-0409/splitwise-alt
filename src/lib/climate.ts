export type Climate = { hi: number; lo: number; rain: 0 | 1 | 2 | 3 };

const nums = (s: string) => s.split(" ").map(Number);

// The usual weather for a place in a month (0 = January). `city` as Loopin
// knows it ("Goa", "Chiang Mai"), `country` an ISO code as the fallback.
export function climateFor(city: string, country: string, month: number): Climate | null {
  const row = C[city.trim().toLowerCase()] ?? (country ? C[country.toUpperCase()] : undefined);
  if (!row || month < 0 || month > 11) return null;
  return { hi: nums(row[0])[month], lo: nums(row[1])[month], rain: Number(row[2][month]) as Climate["rain"] };
}

// The month a trip is mostly in: the middle day's month.
export function tripMonth(start: string, end?: string | null): number {
  const a = Date.parse(`${start}T12:00:00Z`);
  const b = end ? Date.parse(`${end}T12:00:00Z`) : a;
  const mid = new Date(Number.isFinite(b) && b > a ? (a + b) / 2 : a);
  return mid.getUTCMonth();
}

const F = (c: number) => Math.round((c * 9) / 5 + 32);

// In words: "Usually 33° by day, 23° at night. Dry." plus one tip worth
// packing for. `fahrenheit` for visitors from the US.
export function weatherWords(c: Climate, fahrenheit = false): { temps: string; sky: string; line: string; tip: string; icon: string } {
  const t = (n: number) => `${fahrenheit ? F(n) : n}°`;
  const sky =
    c.rain === 3 ? "Monsoon: heavy rain most days." : c.rain === 2 ? "Rainy season: short, heavy showers, often in the afternoon." : c.rain === 1 ? "A shower or two is possible." : c.hi >= 24 ? "Dry and sunny." : "Mostly dry.";
  const temps = `Usually ${t(c.hi)} by day, ${t(c.lo)} at night`;
  const line = `${temps}. ${sky}`;
  const snow = c.lo <= 0 && c.rain >= 1;
  const tip =
    c.rain === 3
      ? "Pack a rain jacket and quick-dry clothes; roads and ferries can be slow."
      : snow
        ? "Snow is possible: warm layers, gloves and good shoes."
        : c.lo <= 2
          ? "Freezing at night: bring a proper jacket and layers."
          : c.hi >= 38
            ? "Very hot: keep the outdoor plans for mornings and evenings."
            : c.rain === 2
              ? "Carry an umbrella and keep the afternoons flexible."
              : c.hi <= 14
                ? "Cool days: jacket weather."
                : c.hi >= 29 && c.rain === 0
                  ? "Pack sunscreen, sunglasses and a water bottle."
                  : c.hi - c.lo >= 14
                    ? "Warm days, cool nights: bring a layer for the evening."
                    : "Easy weather: pack light.";
  const icon = c.rain >= 2 ? "rain" : snow || c.hi <= 8 ? "snow" : c.hi >= 29 && c.rain === 0 ? "sun" : c.rain === 1 ? "cloud" : "sun";
  return { temps, sky, line, tip, icon };
}

